export function getWorkbookTemplateLiveDetail(templateId: number) {
  return WORKBOOK_TEMPLATE_LIVE_DETAILS.find((detail) => detail.id === templateId)
}

export function getConnectedBookSummary(bookId: number) {
  const matches = WORKBOOK_TEMPLATE_LIVE_DETAILS.flatMap((detail) => detail.connectedBooks).filter(([id]) => id === bookId)
  if (!matches.length) return undefined
  const [, title, level] = matches[0]
  return { id: bookId, title, level, rounds: Math.max(...matches.map(([, , , round]) => round)) }
}
